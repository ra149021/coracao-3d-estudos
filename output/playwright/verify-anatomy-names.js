async (page) => {
  const checks = [], errors = [];
  const check = (label, value) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8891/specimens.html?collection=public');
  await page.locator('#load-model').click();
  await page.locator('#anatomy-study').waitFor();
  await page.locator('.anatomy-name:visible').first().waitFor();
  check('Nomes ativos por padrão no coração', await page.locator('#native-names').getAttribute('aria-pressed')==='true');
  check('Nove peças identificadas sem papilares em revisão', await page.locator('#anatomy-part option').count()===10 && !/papilar/i.test(await page.locator('#anatomy-part').textContent()));
  await page.locator('.anatomy-name:visible').first().click();
  check('Clique no nome seleciona a peça e explica sua origem', (await page.locator('#anatomy-part').inputValue()).startsWith('hra_') && (await page.locator('#anatomy-explanation').textContent()).includes('Fonte:'));
  await page.locator('#anatomy-part').selectOption('hra_mitral');
  await page.waitForFunction(()=>[...document.querySelectorAll('.anatomy-name')].some(el=>!el.hidden&&el.dataset.part==='hra_mitral'));
  check('Valva interna é revelada com seu nome e limite', (await page.locator('#anatomy-explanation').textContent()).includes('dois folhetos') && await page.locator('.anatomy-name:visible').count()===1);
  await page.locator('#anatomy-isolate').click();
  check('Isolamento pode ser ativado', await page.locator('#anatomy-isolate').getAttribute('aria-pressed')==='true');
  await page.locator('#native-in').click(); await page.locator('#native-out').click();
  await page.locator('#native-rotate').click();
  await page.waitForFunction(()=>document.querySelector('#native-rotate').getAttribute('aria-pressed')==='true');
  await page.locator('#native-rotate').click();
  await page.locator('#anatomy-reset').click();
  await page.locator('.anatomy-name:visible').first().waitFor();
  check('Ver conjunto restaura nomes principais', await page.locator('#anatomy-part').inputValue()==='' && await page.locator('.anatomy-name:visible').count()>=2);
  await page.locator('#native-names').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('.anatomy-name')].every(el=>el.hidden));
  check('Nomes podem ser ocultados', await page.locator('.anatomy-name:visible').count()===0);
  await page.locator('#native-names').click();
  await page.locator('.anatomy-name:visible').first().waitFor();
  await page.locator('.specimen-stage').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/atlas-nomes-coracao.png'});
  await page.locator('#model-filter').selectOption('respiratory');
  check('Filtro respiratório prioriza modelo com nomes e encerra coração', await page.locator('#model-picker').inputValue()==='respiratory-named' && await page.locator('.anatomy-name').count()===0);
  await page.locator('#load-model').click();
  await page.locator('#anatomy-study').waitFor();
  await page.locator('.anatomy-name:visible').first().waitFor();
  check('Lobos pulmonares têm nomes visíveis', (await page.locator('.anatomy-name:visible').allTextContents()).some(name=>name.includes('lobo')));
  await page.locator('#anatomy-part').selectOption('resp_right_main_bronchus');
  await page.waitForFunction(()=>[...document.querySelectorAll('.anatomy-name')].some(el=>!el.hidden&&el.dataset.part==='resp_right_main_bronchus'));
  check('Brônquio principal pode ser identificado dentro dos lobos', (await page.locator('#anatomy-explanation').textContent()).includes('Brônquio principal direito'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.specimen-stage').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>innerWidth===390&&document.querySelector('#embed-host canvas').getBoundingClientRect().width<390);
  check('Rótulo selecionado e controles cabem no celular', await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&[...document.querySelectorAll('.anatomy-name')].filter(el=>!el.hidden).every(el=>{const b=el.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth;})));
  await page.screenshot({path:'output/playwright/atlas-nomes-respiratorio-mobile.png'});
  await page.locator('#model-picker').selectOption('rijnstate-lung-ct');
  await page.locator('#load-model').click();
  await page.locator('#native-tools').waitFor();
  check('CT sem segmentação não recebe nomes inferidos', await page.locator('.anatomy-name').count()===0 && !await page.locator('#anatomy-study').isVisible() && !await page.locator('#native-names').isVisible());
  await page.goto('http://127.0.0.1:8891/atlas.html?system=respiratory&view=didactic');
  await page.locator('#loading').waitFor({state:'hidden',timeout:45000});
  check('Cena anterior também inicia com nomes ativados', await page.locator('#labels').getAttribute('aria-pressed')==='true');
  check('Nenhum erro JavaScript', errors.length===0);
  return {passed:checks.length,checks,errors};
}
